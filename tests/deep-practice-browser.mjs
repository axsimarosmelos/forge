import assert from 'node:assert/strict';

// Uses the existing Chromium harness and real forms, storage and route changes.
export async function checkDeepPractice({evaluate, route, until, send, screenshot}) {
  const fill = async (id, value) => evaluate(`(() => {const el=document.getElementById(${JSON.stringify(id)});el.value=${JSON.stringify(value)};el.dispatchEvent(new Event(el.tagName==='SELECT'?'change':'input',{bubbles:true}));})()`);
  const submit = id => evaluate(`document.getElementById(${JSON.stringify(id)}).requestSubmit()`);
  await evaluate('ForgeDeepPractice.open("lc-1")');
  await route('#deep', '#deep-start');
  await fill('deep-chunk', 'Trace <script>throw Error(1)</script> safely');
  await fill('deep-criterion', 'Predict the empty-input case without help');
  await submit('deep-start');
  await until('!!document.querySelector("#deep-rep-form")');
  assert.equal(await evaluate('document.querySelectorAll(".deep-session script").length'), 0);
  await fill('deep-attempt', 'Trace the empty input');
  await fill('deep-evidence', 'No iterations');
  await evaluate('ForgeStudy.markHelp("lc-1");ForgeDeepPractice.pause()');
  await send('Page.reload', {ignoreCache: true});
  await until('typeof ForgeDeepPractice!=="undefined" && state.deepPractice.active?.draft.attempt==="Trace the empty input"');
  await evaluate('ForgeWorkspaceStorage.ready');
  assert.equal(await evaluate('state.deepPractice.active.runningSince'), null);
  assert.equal(await evaluate('document.querySelector("#deep-attempt").value'), 'Trace the empty input');
  await submit('deep-rep-form');
  assert.equal(await evaluate('state.deepPractice.active.reps.length'), 0);
  assert.equal(await evaluate('document.querySelector("#deep-outcome").value'), 'guided');
  await fill('deep-mistake', 'Needed the worked trace');
  await fill('deep-adjustment', 'Close the example and trace again');
  await submit('deep-rep-form');
  assert.equal(await evaluate('state.deepPractice.active.reps[0].outcome'), 'guided');
  assert(await evaluate('document.querySelector(".deep-retry").textContent.includes("Close the example")'));
  await fill('deep-attempt', 'Trace with the example closed');
  await fill('deep-evidence', 'Predicted zero iterations and checked it');
  await submit('deep-rep-form');
  assert.equal(await evaluate('ForgeDeepPracticeCore.stats(state.deepPractice.active.reps).repaired'), 1);
  assert.equal(await evaluate('state.study.attempts.length'), 0, 'repetitions never grant platform solves');
  await fill('deep-attempt', 'Trace one item');
  await fill('deep-evidence', 'Visited one invalid index');
  await fill('deep-outcome', 'miss');
  await submit('deep-rep-form');
  assert.equal(await evaluate('state.deepPractice.active.reps.length'), 2, 'native form validation requires diagnosis');
  await fill('deep-mistake', 'Used <= instead of <');
  await fill('deep-adjustment', 'Use the exclusive upper bound');
  await submit('deep-rep-form');
  await fill('deep-attempt', 'Trace the exclusive upper bound');
  await fill('deep-evidence', 'Exactly one valid access');
  await submit('deep-rep-form');
  // Expiry is resilient to throttled/background timers and does not finish work.
  await evaluate('state.deepPractice.active.runningSince=Date.now()-361000;save();render()');
  assert.equal(await evaluate('document.querySelector("#deep-clock").textContent'), '0:00');
  assert.equal(await evaluate('state.deepPractice.sessions.length'), 0);
  await screenshot('deep-practice-desktop');
  await send('Emulation.setDeviceMetricsOverride', {width: 375, height: 812, deviceScaleFactor: 1, mobile: true});
  assert(await evaluate('document.documentElement.scrollWidth<=376'), 'deep practice must fit a mobile viewport');
  await screenshot('deep-practice-mobile');
  await fill('deep-nextStep', 'Rebuild the one-item trace tomorrow');
  await fill('deep-coachNote', 'Ask a peer to check the invariant');
  await submit('deep-finish');
  assert.equal(await evaluate('state.deepPractice.sessions.length'), 1);
  assert.equal(await evaluate('state.deepPractice.sessions[0].elapsedMs'), 360000);
  assert.equal(await evaluate('state.deepPractice.active'), null);
  assert.equal(await evaluate('state.cards.length'), 1);
  assert(await evaluate('state.cards[0].due > Date.now()+86300000'));
  assert(await evaluate('state.journal[0].note.includes("Used <= instead of <")'));
  assert(await evaluate('document.documentElement.scrollWidth<=376'), 'practice notebook must fit a mobile viewport');
  await evaluate('window.deepDownload=download;window.deepBackup=null;download=(name,text)=>{window.deepBackup=JSON.parse(text)};exportData()');
  assert.equal(await evaluate('deepBackup.deepPractice.sessions[0].reps.length'), 4);
  await evaluate('resetProgress();pendingImport=validate(deepBackup);confirmImport();download=deepDownload');
  assert.equal(await evaluate('state.deepPractice.sessions[0].reps.length'), 4);
  await evaluate('resetProgress()');
  await send('Page.reload', {ignoreCache: true});
  await until('typeof ForgeDeepPractice!=="undefined" && ForgeStudy.allProblems().length>20000');
  await evaluate('ForgeWorkspaceStorage.ready');
  assert.equal(await evaluate('state.deepPractice.sessions.length'), 0);
  assert.equal(await evaluate('state.deepPractice.active'), null);
  await send('Emulation.setDeviceMetricsOverride', {width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false});
  await route('#practice', '.problem-row');
}
